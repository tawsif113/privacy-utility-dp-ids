#!/usr/bin/env python3
"""Generate the LaTeX draft from manuscript.md; optionally compile with BibTeX.

Requires Pandoc. --compile also requires pdflatex, bibtex, and the committed figures.
Markdown is the editing source; regenerate LaTeX rather than editing both versions.
"""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / 'paper'
PREAMBLE = r'''% Generated by scripts/build_manuscript.py from paper/manuscript.md.
\documentclass[11pt,a4paper]{article}
\usepackage[margin=22mm]{geometry}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern,textcomp,amsmath,amssymb,microtype}
\usepackage{graphicx,longtable,booktabs,array,calc}
\usepackage{etoolbox}
\usepackage{parskip}
\usepackage[round]{natbib}
\usepackage{xurl}
\usepackage[hidelinks,unicode]{hyperref}
\bibliographystyle{plainnat}
\setcounter{secnumdepth}{-1}
\setlength{\emergencystretch}{3em}
\setlength{\tabcolsep}{4pt}
\renewcommand{\topfraction}{0.9}
\renewcommand{\textfraction}{0.1}
\renewcommand{\floatpagefraction}{0.6}
\AtBeginEnvironment{longtable}{\small}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\makeatletter
\def\maxwidth{\ifdim\Gin@nat@width>\linewidth\linewidth\else\Gin@nat@width\fi}
\def\maxheight{\ifdim\Gin@nat@height>0.65\textheight 0.65\textheight\else\Gin@nat@height\fi}
\makeatother
\setkeys{Gin}{width=\maxwidth,height=\maxheight,keepaspectratio}
\hypersetup{pdftitle={Privacy--Utility Auditing of DP-SGD for Machine-Learning-Based Network Intrusion Detection},pdfauthor={Kazi Md. Tawsif Rahman}}
\title{Privacy--Utility Auditing of DP-SGD for Machine-Learning-Based Network Intrusion Detection}
\author{Kazi Md. Tawsif Rahman\\\small Affiliation to be confirmed}
\date{Author-review draft: 27 October 2026}
\begin{document}
\maketitle
'''


def latex(markdown):
    return subprocess.run(['pandoc', '-f', 'markdown+tex_math_single_backslash', '-t', 'latex', '--natbib'],
                          input=markdown, text=True, check=True, capture_output=True).stdout


def generate():
    source = (PAPER / 'manuscript.md').read_text()
    abstract = source.split('## Abstract\n\n', 1)[1].split('\n**Keywords:**', 1)[0]
    body = '**Keywords:**' + source.split('\n**Keywords:**', 1)[1]
    body = body.split('\n## References', 1)[0]
    def figure(match):
        caption = latex(match[2]).strip()
        return ('\\begin{figure}[htbp]\n\\centering\n'
                '\\includegraphics[width=\\linewidth,height=0.34\\textheight,keepaspectratio]{'
                + match[1] + '}\n\\caption{' + caption + '}\n\\end{figure}')
    body = re.sub(r'!\[[^\]]*\]\(([^)]+)\)\n\n\*Figure \d+\. (.*?)\*', figure, body, flags=re.S)
    text = PREAMBLE + '\n\\begin{abstract}\n' + latex(abstract) + '\n\\end{abstract}\n\n' + latex(body)
    # Pandoc rounds seventh-width columns up; keep the total within the page.
    text = text.replace(r'\real{0.1429}', r'\real{0.14285}')
    text += '\n\\bibliography{references}\n\\end{document}\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compile', action='store_true')
    parser.add_argument('--check', action='store_true', help='Fail if committed LaTeX differs from regenerated output.')
    args = parser.parse_args()
    text = generate()
    path = PAPER / 'manuscript.tex'
    if args.check:
        assert path.read_text() == text, 'Regenerate manuscript.tex from manuscript.md.'
        print('Markdown and LaTeX are synchronized.')
    else:
        path.write_text(text)
        print('Generated paper/manuscript.tex.')
    if args.compile:
        for command in [['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'manuscript.tex'],
                        ['bibtex', 'manuscript'],
                        ['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'manuscript.tex'],
                        ['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'manuscript.tex']]:
            run = subprocess.run(command, cwd=PAPER, text=True, capture_output=True)
            if run.returncode:
                raise RuntimeError(run.stdout[-6000:] + run.stderr[-2000:])
        log = (PAPER / 'manuscript.log').read_text()
        warnings = [line for line in log.splitlines() if 'Warning' in line or 'Overfull' in line]
        print('\n'.join(warnings) if warnings else 'Compiled with no LaTeX warnings or overfull boxes.')
        print('PDF: paper/manuscript.pdf')


if __name__ == '__main__':
    main()
